import React, { createContext, useContext, useState, useEffect, ReactNode } from 'react';

type Mode = 'impact' | 'calm';
type Language = 'en' | 'hi' | 'bn' | 'ta' | 'te' | 'mr';

interface AppContextType {
  mode: Mode;
  toggleMode: () => void;
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: string) => string;
  reducedMotion: boolean;
  toggleReducedMotion: () => void;
  highContrast: boolean;
  toggleHighContrast: () => void;
}

const AppContext = createContext<AppContextType | undefined>(undefined);

export const useApp = () => {
  const context = useContext(AppContext);
  if (!context) {
    throw new Error('useApp must be used within AppProvider');
  }
  return context;
};

interface AppProviderProps {
  children: ReactNode;
}

export const AppProvider: React.FC<AppProviderProps> = ({ children }) => {
  const [mode, setMode] = useState<Mode>(() => {
    return (localStorage.getItem('voiceguard-mode') as Mode) || 'impact';
  });
  
  const [language, setLanguageState] = useState<Language>(() => {
    return (localStorage.getItem('voiceguard-lang') as Language) || 'en';
  });
  
  const [reducedMotion, setReducedMotion] = useState(false);
  const [highContrast, setHighContrast] = useState(false);

  useEffect(() => {
    document.body.setAttribute('data-mode', mode);
    localStorage.setItem('voiceguard-mode', mode);
  }, [mode]);

  useEffect(() => {
    localStorage.setItem('voiceguard-lang', language);
  }, [language]);

  useEffect(() => {
    if (reducedMotion) {
      document.body.classList.add('reduced-motion');
    } else {
      document.body.classList.remove('reduced-motion');
    }
  }, [reducedMotion]);

  useEffect(() => {
    if (highContrast) {
      document.body.classList.add('high-contrast');
    } else {
      document.body.classList.remove('high-contrast');
    }
  }, [highContrast]);

  const toggleMode = () => {
    setMode(prev => prev === 'impact' ? 'calm' : 'impact');
  };

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
  };

  const toggleReducedMotion = () => {
    setReducedMotion(prev => !prev);
  };

  const toggleHighContrast = () => {
    setHighContrast(prev => !prev);
  };

  const t = (key: string): string => {
    // @ts-ignore - Allows dynamic access to translation keys
    return translations[language]?.[key] || translations.en[key] || key;
  };

  const value: AppContextType = {
    mode,
    toggleMode,
    language,
    setLanguage,
    t,
    reducedMotion,
    toggleReducedMotion,
    highContrast,
    toggleHighContrast,
  };

  return <AppContext.Provider value={value}>{children}</AppContext.Provider>;
};

